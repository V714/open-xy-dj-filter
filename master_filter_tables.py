"""Generate 44.1 kHz TPT-SVF targets; no trigonometry or division in audio ticks."""
import math
from pathlib import Path


def generate():
    lines = ['// Generated by master_filter_tables.py; Q2.29, 44100 Hz.',
             '#include "master_filter.hpp"',
             'namespace opxy { namespace extensions { namespace dj {',
             'const Coefficients coefficients[2][513] = {']
    for high in (False, True):
        lines.append('    {')
        for distance in range(513):
            d = distance / 512
            t = min(distance / 51, 1)
            q = math.sqrt(.5) + (1.25 - math.sqrt(.5)) * t * t * (3 - 2 * t)
            # Spread the useful former ~10..90 travel over the whole knob.
            # Keep the neutral-side targets transparent (HP20 / LP20000 Hz),
            # but leave an audible residual band at the two extremes.
            frequency = 20 * 250 ** d if high else 20000 * 250 ** -d
            g, k = math.tan(math.pi * frequency / 44100), 1 / q
            a1 = 1 / (1 + g * (g + k))
            # Bound the resonant frequency response by unity. No new limiter.
            peak = 1 if q <= math.sqrt(.5) else q / math.sqrt(1 - 1 / (4 * q * q))
            values = (a1, g * a1, g * g * a1, k, 1 / peak)
            lines.append('        {' + ', '.join(str(round(x * (1 << 29))) for x in values) + '},')
        lines.append('    },')
    lines.extend(['};', '}}}', ''])
    return '\n'.join(lines)


if __name__ == '__main__':
    Path(__file__).with_name('master_filter_tables.cpp').write_text(generate(), encoding='utf-8', newline='\n')
